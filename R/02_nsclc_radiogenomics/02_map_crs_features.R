  file = "02_metadata/crs_nonzero_feature_mapping.rds"
)

saveRDS(
  list(
    intercept = intercept_value,
    symbol_coefficients = coef_symbol,
    nonzero_feature_map = coef_nonzero_map,
    decision = decision,
    note = "Coefficients are aggregated by Gene Symbol when multiple Ensembl features map to the same symbol."
  ),
  file = "06_models/crs_gene_symbol_coefficients.rds"
)

